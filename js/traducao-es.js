    const entradas = Object.entries(traducoes)
        .filter(([origem, destino]) => origem !== destino)
        .sort(([a], [b]) => b.length - a.length)
        .map(([origem, destino]) => {
            const escaparRegex = (texto) => texto
                .split(/(\s+)/)
                .map((parte) => /^\s+$/.test(parte) ? '\\s+' : parte.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))
                .join('');
            const limiteInicio = /^[\p{L}\p{N}_]/u.test(origem);
            const limiteFim = /[\p{L}\p{N}_]$/u.test(origem);
            const antes = limiteInicio ? '(?<![\\p{L}\\p{N}_])' : '';
            const depois = limiteFim ? '(?![\\p{L}\\p{N}_])' : '';
            return [new RegExp(`${antes}${escaparRegex(origem)}${depois}`, 'giu'), origem, destino];
        });
    const expressoes = new RegExp(entradas.map(([expressao]) => `(?:${expressao.source})`).join('|'), 'giu');
    const traducoesExatas = new Map(entradas.map(([, origem, destino]) => [origem, destino]));
    const traducoesPorOrigem = new Map(entradas.map(([, origem, destino]) => [origem.toLocaleLowerCase(), destino]));
    const traduzirTexto = (valor) => {
        const texto = String(valor);
        if (!texto.trim()) return texto;
        const espacoInicial = texto.match(/^\s*/u)[0];
        const espacoFinal = texto.match(/\s*$/u)[0];
        const conteudo = texto.slice(espacoInicial.length, texto.length - espacoFinal.length).replace(/\s+/gu, ' ');
        const traduzido = conteudo.replace(expressoes, (correspondencia) => {
        if (correspondencia === 'sobre') return correspondencia;
        return traducoesExatas.get(correspondencia) ?? traducoesPorOrigem.get(correspondencia.toLocaleLowerCase()) ?? correspondencia;
        });
        return espacoInicial + traduzido + espacoFinal;
    };
    window.traduzirTexto = traduzirTexto;

    const atributosTraduziveis = ['placeholder', 'aria-label', 'title', 'alt', 'content', 'data-title', 'data-description', 'data-sectors', 'data-tag', 'data-category-filter'];
    const nosTraduzidos = new WeakSet();

    function traduzirNo(no) {
        if (no.nodeType === Node.TEXT_NODE) {
            if (nosTraduzidos.has(no)) return;
            const textoTraduzido = traduzirTexto(no.nodeValue);
            if (textoTraduzido !== no.nodeValue) {
                no.nodeValue = textoTraduzido;
                nosTraduzidos.add(no);
            }
            return;
        }
        if (no.nodeType !== Node.ELEMENT_NODE || ['SCRIPT', 'STYLE'].includes(no.tagName)) return;

        atributosTraduziveis.forEach((atributo) => {
            if (no.hasAttribute(atributo)) {
                const valor = traduzirTexto(no.getAttribute(atributo));
                if (valor !== no.getAttribute(atributo)) no.setAttribute(atributo, valor);
            }
        });
        no.childNodes.forEach(traduzirNo);
    }

    traduzirNo(document.body);
    document.title = traduzirTexto(document.title);
    document.querySelector('meta[name="description"]')?.setAttribute('content', traduzirTexto(document.querySelector('meta[name="description"]')?.content || ''));
    new MutationObserver((mutacoes) => {
        mutacoes.forEach((mutacao) => {
            if (mutacao.type === 'characterData') traduzirNo(mutacao.target);
            mutacao.addedNodes.forEach(traduzirNo);
        });
    }).observe(document.body, { subtree: true, childList: true, characterData: true });
